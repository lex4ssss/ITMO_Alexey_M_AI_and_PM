EMAILS = ["ivan.petrov@example.com", "a.smirnova@mail.example", "user1987@example.org"]
PHONES = ["+7 999 123-45-67", "89161234567", "+7(812)555-00-11"]
CARDS = ["4276 1600 1234 5678", "5536913812345678"]
ORDERS = ["A-104839", "B-772019", "C-330551"]


def fill(text):
    return (text.replace("{email}", random.choice(EMAILS))
                .replace("{phone}", random.choice(PHONES))
                .replace("{card}", random.choice(CARDS))
                .replace("{order}", random.choice(ORDERS)))


def build(n_per_class=26):
    rows = []
    tid = 1000
    for label, texts in TEMPLATES.items():
        for i in range(n_per_class):
            base = fill(random.choice(texts))
            text = base + random.choice(NOISE)
            if random.random() < 0.25:
                text = text.upper() if random.random() < 0.4 else text.capitalize()
            rows.append({
                "ticket_id": f"T-{tid}",
                "channel": random.choice(CHANNELS),
                "text": text,
                "label": label,
            })
            tid += 1
    random.shuffle(rows)
    return rows


if __name__ == "__main__":
    out = Path(__file__).with_name("tickets.jsonl")
    rows = build()
    with out.open("w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"{len(rows)} тикетов -> {out}")
